"""Write editable Mandarin narration against the encoded MP4's actual frame timeline."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[3]
PROJECT=ROOT/'docs/submission/demo-2026-10-18'
EVIDENCE=ROOT/'docs/evidence/formal-demo-2026-10-18'
meta=json.loads((EVIDENCE/'video-verification.json').read_text(encoding='utf-8'))
chapters={c['id']:c for c in meta['chapters']}
texts={
 'intro':'这是图证，一款面向普通读者的图表证据审计台。刷到一张图，数字和配文看起来都很确定，但它们真的有依据吗？图证从截图出发，先检查图内关系，再对照适用来源，让每一项判断都能回到具体数字和证据。',
 'vision':'先上传一张团队自制的营业收入图。图上标着去年八十、今年一百，标题却写增长百分之四十。点击读取后，页面中的观察值来自这次真实模型请求。模型负责读图，程序负责计算；用户确认后，才形成图内结论。\n\n按八十到一百计算，增长率是百分之二十五。把今年数值手动改成九十六，重新确认，结果随之变化；再改回一百，重新计算。用户修改和原图摘录分开记录。这里核对的是截图内部关系，还没有验证现实世界的数据。',
 'source':'接下来进入来源核验。首页载入的是团队自制 CPI 图片和配文，载入本身不调用模型。图中写着百分之零点八，配文却说比上月上涨百分之零点八；同比与环比，是这次要核对的关键。\n\n点击运行后，模型实际读取图文、拆出主张，再选择允许使用的工具。本次配文中的环比百分之零点八，与所引来源的环比百分之零点二不一致；图上没有写明比较方式的观察，则继续保留待核对。配文判断与图内观察分开列出，每项都能查看依据。',
 'citations':'一条结论需要能回到来源。这里展示本次采用的资料、发布单位、发布日期和原始链接，并保留适用月份、范围、比较方式与内容指纹。\n\n图证当前检索的是收录的固定公开资料库，不是全网搜索。检索命中也不等于证据适用，资料覆盖不到的说法，不能强行给出确定答案。',
 'trace':'再展开实际工具轨迹。这里能看到模型选择了什么工具、程序收到哪些参数、返回了什么结果，以及调查为什么结束。画面对应本次执行记录，不是预排动画。\n\n模型提供语义理解和行动选择，程序限制可用工具与调用预算，并校验引用和口径。我们展示这些可复查的行动与结果，让判断过程能够被检查。',
 'rewrite':'核验之后，图证可以给出带依据的修改建议。逐处展开，能查看原句、建议写法、处理理由与相关引用。建议先展示给用户，用户主动采用后才写入配文。\n\n采用改变了当前输入，旧结果因此进入历史，不再代表现在的配文。画面没有再次运行核验，所以不能把采用建议说成新配文已经通过复验。',
 'clarify':'再看一个口径不完整的例子：“十二月 CPI 上涨百分之零点八”，没有说明同比还是环比。模型不能替用户决定这句话想表达什么，所以提出一个会影响判断的具体问题。\n\n补充“同比”后，系统沿同一条调查继续执行，保留补充内容和结论前后的变化。用户的回答标记为用户提供，只用来明确原句的比较方式，不会冒充官方数据。页面还会保留没有解决的内容，补了一条信息也不意味着整张图的所有问题都已消失。',
 'recovery':'最后实际选择一个不支持的文本文件，页面立即提示图片格式要求。换成合法 PNG 后，错误消失，图片恢复显示。这里演示的是输入格式错误的恢复，没有发起模型请求。',
 'outro':'图证把模型读取、人工确认、程序计算和来源引用连接起来。它帮助读者看清一张图、一段话的依据，也留下目前无法判断的部分，让结论有据可查。',
}
if not chapters['vision']['result'].get('manualRecalculation'):
    texts['vision']='先上传团队自制的营业收入图，点击读取。页面中的文字和数值来自这次真实模型请求，图上原始摘录保留供人工核对。\n\n模型负责读图和拆解主张，用户确认后，程序才执行计算。每条主张保留自己的观察和依据，图内核对不代表现实世界的数据已经核实。'
if not chapters['rewrite']['result'].get('adopted'):
    texts['rewrite']='核验之后，我们查看本次能安全生成的修改建议及未解决项。没有依据的内容不能因为文字流畅就变成事实。这里保留实际返回的状态，由用户决定是否继续补证或修改原文，画面没有把未完成的复验说成已经通过。'
if not chapters['clarify']['result'].get('clarificationAsked'):
    texts['clarify']='再看一句口径不完整的配文：“十二月 CPI 上涨百分之零点八”，没有说明同比还是环比。同比是和去年同月比较，环比是和上个月比较；两者都描述变化，却不是同一回事。\n\n虽然图中提到了同比，系统也没有仅凭数值相等，就替配文认定比较方式。这次返回保留了待核对项，没有触发追问表单。我们展开真实结论、停止原因和未解决项，查看还缺什么。用户可以补齐比较方式后再核验，当前画面仍保留本次未确认的状态。'
def clock(value, end=False):
    seconds=round(value)
    return f'{seconds//60:02}:{seconds%60:02}'
intro=f'# 图证比赛视频配音时间轴\n\n对应[无声 MP4](../{Path(meta["path"]).name})，实际时长 {meta["seconds"]:.3f} 秒，1920×1080 / 30 fps。画面为 2026-10-18 当前生产界面的实机操作，AI 段为本次官方真实请求。没有自动配音或背景音乐。\n\n时间以本成片为准；下表四舍五入到整秒，精确位置见 [chapters.srt](chapters.srt)。建议每段前后留少量停顿，不必把区间填满。\n\n| 配音区间 | 内容 | 画面要点 |\n| --- | --- | --- |\n'
for c in meta['chapters']:
    intro+=f'| {clock(c["start"])}–{clock(c["end"],True)} | {c["title"]} | {"本次模型实录" if c["rawPart"]=="live" else "实际页面操作，无模型请求"} |\n'
for c in meta['chapters']:
    text=texts[c['id']]
    intro+=f'\n## {clock(c["start"])}–{clock(c["end"],True)} {c["title"]}\n\n{text}\n'
intro+='\n## 配音注意\n\n- 可按个人语速改写，数字、引用、模型返回状态和证据范围要与画面一致。\n- “模型读图”“用户补充”“程序计算”“公开来源”应分开表述。\n- 本片展示产品路径，不据此宣称独立盲审增益、整体模型可靠性或用户研究收益。\n- 加入普通话人声并完成最终人工检查后，才是可提交的有声赛事版。\n'
if not chapters['clarify']['result'].get('clarificationAsked'):
    intro+='- 本次口径不明片段没有触发追问，也没有执行 resume；讲解中不要说成已经完成补证恢复。\n'
(PROJECT/'voiceover.md').write_text(intro,encoding='utf-8')
print('Written voiceover.md against',meta['frames'],'encoded frames.')
